NUTRIENT_IDS = {"calories": 1008, "protein": 1003, "fat": 1004, "carbs": 1005}


def decimal_literal(value: float) -> str:
    """Format a USDA number without binary-float artifacts."""
    return format(Decimal(str(value)).normalize(), "f")


def main() -> None:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    foods_by_id = {item["fdcId"]: item for item in data["SurveyFoods"] if item}
    lines = [
        '"""Curated USDA FNDDS 2021-2023 foods; nutrient values are per 100 grams."""',
        "",
        "from app.data.base_foods import BaseFood, food",
        "",
        "FNDDS_FOODS: tuple[BaseFood, ...] = (",
    ]
    for fdc_id, name in FOOD_NAMES.items():
        item = foods_by_id.get(fdc_id)
        if item is None:
            raise ValueError(f"FNDDS food {fdc_id} is missing from {SOURCE}")
        values = {
            nutrient["nutrient"]["id"]: nutrient["amount"]
            for nutrient in item["foodNutrients"]
            if nutrient.get("nutrient") and "amount" in nutrient
        }
        missing = set(NUTRIENT_IDS.values()) - values.keys()
        if missing:
            raise ValueError(f"FNDDS food {fdc_id} lacks nutrient IDs: {sorted(missing)}")
        nutrients = [decimal_literal(values[NUTRIENT_IDS[key]]) for key in NUTRIENT_IDS]
        rendered_name = json.dumps(name, ensure_ascii=False)
        lines.append(
            f"    food({fdc_id}, {rendered_name}, "
            f"{', '.join(json.dumps(value) for value in nutrients)}, source=\"USDA_FNDDS\"),"
        )
    lines.extend((")", ""))
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {len(FOOD_NAMES)} FNDDS foods to {OUTPUT}")


if __name__ == "__main__":
    main()
